#!/usr/bin/env python3
"""
Evaluates Phase 3/4's hybrid retrieval endpoint against a fixed set of
hand-curated queries with known-relevant products, and reports
precision@5, precision@10, and latency per query plus aggregates.

Ground truth (eval/queries.json) is generated from the actual seeded
catalog by filtering on title/category/price, not typed by hand — see
the generator note at the top of that file. That keeps it correct for
this project's deterministic synthetic catalog (Phase 1, seed=42)
without needing manual re-curation if the catalog is regenerated.

Usage:
    # against a running local server (default http://localhost:8000):
    backend/.venv/bin/python eval/run_eval.py

    # against a different host, e.g. a deployed instance:
    backend/.venv/bin/python eval/run_eval.py --base-url https://your-app.example.com

Requires the catalog to be seeded AND ingested (embeddings + tsvector
populated — see Phase 2) for results to be meaningful; against an
un-ingested catalog every precision score will be near zero, since
vector search has nothing to compare against and keyword search alone
carries the ranking.
"""

import argparse
import json
import statistics
import time
from pathlib import Path

import requests

EVAL_DIR = Path(__file__).resolve().parent
QUERIES_PATH = EVAL_DIR / "queries.json"
RESULTS_PATH = EVAL_DIR / "results.md"


def precision_at_k(returned_ids: list[str], relevant_ids: set[str], k: int) -> float:
    top_k = returned_ids[:k]
    if not top_k:
        return 0.0
    hits = sum(1 for ext_id in top_k if ext_id in relevant_ids)
    return hits / len(top_k)


def run_query(base_url: str, query: str, top_k: int = 10) -> tuple[list[str], float]:
    """Returns (ranked external_ids, latency_seconds)."""
    start = time.perf_counter()
    response = requests.get(
        f"{base_url}/api/search/", params={"q": query, "top_k": top_k}, timeout=30,
    )
    latency = time.perf_counter() - start
    response.raise_for_status()
    body = response.json()
    returned_ids = [r["product"]["external_id"] for r in body["results"]]
    return returned_ids, latency


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base-url", default="http://localhost:8000")
    args = parser.parse_args()

    queries = json.loads(QUERIES_PATH.read_text())["queries"]

    rows = []
    for entry in queries:
        query_text = entry["query"]
        relevant = set(entry["relevant_external_ids"])

        try:
            returned_ids, latency = run_query(args.base_url, query_text)
            error = None
        except requests.RequestException as exc:
            returned_ids, latency, error = [], None, str(exc)

        p5 = precision_at_k(returned_ids, relevant, 5) if error is None else None
        p10 = precision_at_k(returned_ids, relevant, 10) if error is None else None

        rows.append({
            "query": query_text,
            "precision_at_5": p5,
            "precision_at_10": p10,
            "latency_ms": latency * 1000 if latency is not None else None,
            "error": error,
        })

    render_and_save(rows, args.base_url)


def render_and_save(rows: list[dict], base_url: str):
    ok_rows = [r for r in rows if r["error"] is None]

    lines = ["| Query | Precision@5 | Precision@10 | Latency (ms) |", "|---|---|---|---|"]
    for r in rows:
        if r["error"] is not None:
            lines.append(f"| {r['query']} | — | — | error: {r['error'][:60]} |")
        else:
            lines.append(
                f"| {r['query']} | {r['precision_at_5']:.2f} | "
                f"{r['precision_at_10']:.2f} | {r['latency_ms']:.0f} |"
            )

    if ok_rows:
        avg_p5 = statistics.mean(r["precision_at_5"] for r in ok_rows)
        avg_p10 = statistics.mean(r["precision_at_10"] for r in ok_rows)
        avg_latency = statistics.mean(r["latency_ms"] for r in ok_rows)
        lines.append(
            f"| **Average ({len(ok_rows)}/{len(rows)} queries)** | "
            f"**{avg_p5:.2f}** | **{avg_p10:.2f}** | **{avg_latency:.0f}** |"
        )
    else:
        lines.append("| **Average** | — | — | all queries errored |")

    table = "\n".join(lines)
    print(f"\nResults against {base_url}\n")
    print(table)

    RESULTS_PATH.write_text(
        f"<!-- Generated by eval/run_eval.py against {base_url} -->\n\n{table}\n"
    )
    print(f"\nSaved to {RESULTS_PATH}")


if __name__ == "__main__":
    main()
